public class Switchcaseprogram {
    public static void main(String[]args){
        int day=6;
        switch(day){
            case 1:
                System.out.println("Its Monday bro!");
                break;
            case 2:
                System.out.println("Its Tuesday bro!");
                break;
            case 3:
                System.out.println("Its Wednesday bro!");
                break;
            case 4:
                System.out.println("Its Thursday bro!");
                break;
            case 5:
                System.out.println("Its Friday bro!");
                break;
            case 6:
                System.out.println("Its Saturday bro!");
                break;
            case 7:   
                System.out.println("Its Sunday bro!");
                break;
            default:
                System.out.println("Fuck you bro! Enter a valid day number.");
        }
    }
}
